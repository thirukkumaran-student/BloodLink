"""Canonical error codes and their HTTP mapping (owner: D1, spec §14).

Feature developers raise domain exceptions carrying one of these codes; the API
exception layer converts them into the canonical error envelope. Internal stack
traces are never exposed.
"""

from __future__ import annotations

from enum import Enum


class ErrorCode(str, Enum):
    # transport / generic
    VALIDATION_ERROR = "VALIDATION_ERROR"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    CONFLICT = "CONFLICT"
    UNPROCESSABLE = "UNPROCESSABLE"
    RATE_LIMITED = "RATE_LIMITED"
    INTERNAL_ERROR = "INTERNAL_ERROR"

    # identity / orgs (D1)
    EMAIL_ALREADY_REGISTERED = "EMAIL_ALREADY_REGISTERED"
    INVALID_CREDENTIALS = "INVALID_CREDENTIALS"
    TOKEN_EXPIRED = "TOKEN_EXPIRED"
    TOKEN_INVALID = "TOKEN_INVALID"
    ORGANIZATION_NOT_VERIFIED = "ORGANIZATION_NOT_VERIFIED"
    ORGANIZATION_SUSPENDED = "ORGANIZATION_SUSPENDED"
    ORGANIZATION_NOT_FOUND = "ORGANIZATION_NOT_FOUND"

    # patient needs (D2)
    NEED_NOT_FOUND = "NEED_NOT_FOUND"
    NEED_ALREADY_REVIEWED = "NEED_ALREADY_REVIEWED"
    NEED_REQUIRED_BY_IN_PAST = "NEED_REQUIRED_BY_IN_PAST"
    NEED_NOT_CANCELLABLE = "NEED_NOT_CANCELLABLE"

    # blood requests (D3)
    REQUEST_NOT_FOUND = "REQUEST_NOT_FOUND"
    REQUEST_INVALID_TRANSITION = "REQUEST_INVALID_TRANSITION"
    REQUEST_NOT_OPEN_FOR_RESPONSES = "REQUEST_NOT_OPEN_FOR_RESPONSES"
    REQUEST_TERMINAL = "REQUEST_TERMINAL"
    DONOR_NOT_SELECTABLE = "DONOR_NOT_SELECTABLE"

    # responses (D4)
    RESPONSE_NOT_FOUND = "RESPONSE_NOT_FOUND"
    RESPONSE_ALREADY_EXISTS = "RESPONSE_ALREADY_EXISTS"
    CONFIRMATION_REQUIRED = "CONFIRMATION_REQUIRED"
    DONOR_NOT_ELIGIBLE_FOR_OUTREACH = "DONOR_NOT_ELIGIBLE_FOR_OUTREACH"
    DONOR_IN_COOLDOWN = "DONOR_IN_COOLDOWN"
    DONOR_PROFILE_REQUIRED = "DONOR_PROFILE_REQUIRED"
    ORGANIZATION_RESPONSE_EXISTS = "ORGANIZATION_RESPONSE_EXISTS"

    # communication (D4)
    CONVERSATION_NOT_FOUND = "CONVERSATION_NOT_FOUND"
    CONVERSATION_CLOSED = "CONVERSATION_CLOSED"
    NOT_A_PARTICIPANT = "NOT_A_PARTICIPANT"
    MESSAGE_TOO_LONG = "MESSAGE_TOO_LONG"

    # donations (D4)
    DONATION_CONFIRMATION_INCOMPLETE = "DONATION_CONFIRMATION_INCOMPLETE"
    DONATION_ALREADY_CONFIRMED = "DONATION_ALREADY_CONFIRMED"

    # privacy (D1)
    PRIVACY_VIOLATION = "PRIVACY_VIOLATION"


HTTP_STATUS_FOR: dict[ErrorCode, int] = {
    ErrorCode.VALIDATION_ERROR: 422,
    ErrorCode.UNAUTHENTICATED: 401,
    ErrorCode.FORBIDDEN: 403,
    ErrorCode.NOT_FOUND: 404,
    ErrorCode.CONFLICT: 409,
    ErrorCode.UNPROCESSABLE: 422,
    ErrorCode.RATE_LIMITED: 429,
    ErrorCode.INTERNAL_ERROR: 500,
    ErrorCode.EMAIL_ALREADY_REGISTERED: 409,
    ErrorCode.INVALID_CREDENTIALS: 401,
    ErrorCode.TOKEN_EXPIRED: 401,
    ErrorCode.TOKEN_INVALID: 401,
    ErrorCode.ORGANIZATION_NOT_VERIFIED: 403,
    ErrorCode.ORGANIZATION_SUSPENDED: 403,
    ErrorCode.ORGANIZATION_NOT_FOUND: 404,
    ErrorCode.NEED_NOT_FOUND: 404,
    ErrorCode.NEED_ALREADY_REVIEWED: 409,
    ErrorCode.NEED_REQUIRED_BY_IN_PAST: 422,
    ErrorCode.NEED_NOT_CANCELLABLE: 409,
    ErrorCode.REQUEST_NOT_FOUND: 404,
    ErrorCode.REQUEST_INVALID_TRANSITION: 409,
    ErrorCode.REQUEST_NOT_OPEN_FOR_RESPONSES: 409,
    ErrorCode.REQUEST_TERMINAL: 409,
    ErrorCode.DONOR_NOT_SELECTABLE: 409,
    ErrorCode.RESPONSE_NOT_FOUND: 404,
    ErrorCode.RESPONSE_ALREADY_EXISTS: 409,
    ErrorCode.CONFIRMATION_REQUIRED: 422,
    ErrorCode.DONOR_NOT_ELIGIBLE_FOR_OUTREACH: 409,
    ErrorCode.DONOR_IN_COOLDOWN: 409,
    ErrorCode.DONOR_PROFILE_REQUIRED: 409,
    ErrorCode.ORGANIZATION_RESPONSE_EXISTS: 409,
    ErrorCode.CONVERSATION_NOT_FOUND: 404,
    ErrorCode.CONVERSATION_CLOSED: 409,
    ErrorCode.NOT_A_PARTICIPANT: 403,
    ErrorCode.MESSAGE_TOO_LONG: 422,
    ErrorCode.DONATION_CONFIRMATION_INCOMPLETE: 409,
    ErrorCode.DONATION_ALREADY_CONFIRMED: 409,
    ErrorCode.PRIVACY_VIOLATION: 500,
}


def http_status(code: ErrorCode) -> int:
    return HTTP_STATUS_FOR.get(code, 400)
